#!/usr/bin/env python3
"""Extract the few icons the site uses from the icon fonts into inline-SVG data.

Replaces the Semantic UI / Academicons icon *fonts* (several 50-500 KB font
files per format) with ~12 inline SVG paths. Writes src/components/icons-data.js,
which src/components/Icon.jsx renders.

To add an icon: look up its codepoint in
node_modules/semantic-ui-css/components/icon.min.css (e.g.
`i.icon.trophy:before{content:"\\f091"}`; outline variants live in the
outline font), add it to ICONS below, and rerun:

    python3 scripts/build-icons.py
"""
import json
import re

FA = 'node_modules/semantic-ui-css/themes/default/assets/fonts/'
FONTS = {
    'solid': FA + 'icons.svg',
    'outline': FA + 'outline-icons.svg',
    'brand': FA + 'brand-icons.svg',
    'academicons': 'libs/academicons/fonts/academicons.svg',
}

# icon name (Semantic class order) -> (font, codepoint)
ICONS = {
    'trophy': ('solid', 'f091'),
    'file outline': ('outline', 'f15b'),
    'file alternate outline': ('outline', 'f15c'),
    'file pdf outline': ('outline', 'f1c1'),
    'github square': ('brand', 'f092'),
    'assistive listening systems': ('solid', 'f2a2'),
    'volume up': ('solid', 'f028'),
    'arrow right': ('solid', 'f061'),
    'arrow left': ('solid', 'f060'),
    'window close': ('solid', 'f410'),
    'close': ('solid', 'f00d'),
    'google scholar square': ('academicons', 'e9f9'),
}

# all four fonts: units-per-em 512, ascent 448 (glyph y axis points up)
ASCENT, EM = 448, 512


def glyph(font_file, cp):
    svg = open(font_file, encoding='utf-8').read()
    for m in re.finditer(r'<glyph\b(.*?)/?>', svg, re.S):
        attrs = dict(re.findall(r'([\w-]+)="([^"]*)"', m.group(1)))
        if attrs.get('unicode', '').lower() == '&#x%s;' % cp:
            default_adv = re.search(r'<font\b[^>]*horiz-adv-x="([\d.]+)"', svg).group(1)
            return attrs['d'], float(attrs.get('horiz-adv-x', default_adv))
    raise SystemExit('glyph %s not found in %s' % (cp, font_file))


def flip(d):
    """Mirror a glyph path vertically (font y-up -> SVG y-down) by negating
    every y coordinate, so the output needs no transform attribute."""
    out, cmd, args = [], None, []
    tokens = re.findall(r'[A-Za-z]|-?(?:\d+\.?\d*|\.\d+)(?:e-?\d+)?', d)

    def emit():
        if cmd is None:
            return
        u = cmd.upper()
        nums = [float(a) for a in args]
        if u in 'MLT':
            nums = [v if i % 2 == 0 else -v for i, v in enumerate(nums)]
        elif u in 'CSQ':
            nums = [v if i % 2 == 0 else -v for i, v in enumerate(nums)]
        elif u == 'V':
            nums = [-v for v in nums]
        elif u == 'A':
            # rx ry rot large sweep x y: flip sweep and y
            for i in range(0, len(nums), 7):
                nums[i + 4] = 1 - nums[i + 4]
                nums[i + 6] = -nums[i + 6]
        out.append(cmd + ' '.join(('%.2f' % v).rstrip('0').rstrip('.') for v in nums))

    for t in tokens:
        if t.isalpha():
            emit()
            cmd, args = t, []
        else:
            args.append(t)
    emit()
    return ''.join(out).replace(' -', '-')


data = {}
for name, (font, cp) in ICONS.items():
    d, adv = glyph(FONTS[font], cp)
    # viewBox: x 0..advance, y -ascent..descent (after flipping)
    data[name] = {'w': round(adv, 2), 'd': flip(d)}

with open('src/components/icons-data.js', 'w') as f:
    f.write('// Generated by scripts/build-icons.py from the icon fonts. Do not edit.\n')
    f.write('// viewBox for each icon: `0 -%d ${w} %d`\n' % (ASCENT, EM))
    f.write('export const ICON_ASCENT = %d\nexport const ICON_EM = %d\n' % (ASCENT, EM))
    f.write('export const ICONS = ' + json.dumps(data, indent=1) + '\n')
print('wrote %d icons to src/components/icons-data.js' % len(data))
